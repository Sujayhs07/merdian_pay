export interface PaymentStatusBadgeProps {
  status: "paid" | "completed" | "pending" | "processing" | "failed" | "error" | "expired" | "cancelled";
  sourceChain?: "solana" | "ethereum" | null;
  size?: "sm" | "md";
  className?: string;
  style?: React.CSSProperties;
}

export function PaymentStatusBadge({
  status,
  sourceChain,
  size = "md",
  className = "",
  style,
}: PaymentStatusBadgeProps) {
  const isSm = size === "sm";
  const iconSize = isSm ? 11 : 13;

  if (status === "paid" || status === "completed") {
    return (
      <span className={`status-pill paid ${className}`} style={style}>
        <IconCheckCircle size={iconSize} />
        <span>Settled</span>
        {sourceChain === "ethereum" && (
          <span style={{ opacity: 0.8, fontSize: "0.85em", marginLeft: 2 }}>· CCTP</span>
        )}
      </span>
    );
  }

  if (status === "pending" || status === "processing") {
    return (
      <span className={`status-pill pending ${className}`} style={style}>
        <IconClock size={iconSize} />
        <span>Pending</span>
      </span>
    );
  }

  if (status === "failed" || status === "error") {
    return (
      <span className={`status-pill failed ${className}`} style={style}>
        <IconXCircle size={iconSize} />
        <span>Failed</span>
      </span>
    );
  }

  return (
    <span className={`status-pill expired ${className}`} style={style}>
      <IconSlashCircle size={iconSize} />
      <span>{status === "cancelled" ? "Cancelled" : "Expired"}</span>
    </span>
  );
}

